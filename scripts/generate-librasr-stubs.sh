#!/usr/bin/env bash
# Generates the type stubs src/Tools/LibRASR/librasr.pyi from a built librasr module.
# Regenerate them whenever the python bindings change, the CI checks that they are up to date.
#
# Requires: pip install pybind11-stubgen==3.0.0
# Usage: scripts/generate-librasr-stubs.sh [directory containing the built librasr*.so, default: build/src/Tools/LibRASR]
set -euo pipefail
cd "$(dirname "$0")/.."

module_dir="$(realpath "${1:-build/src/Tools/LibRASR}")"
output_dir="$(mktemp -d)"
trap 'rm -rf "${output_dir}"' EXIT

PYTHONPATH="${module_dir}" pybind11-stubgen librasr --numpy-array-wrap-with-annotated --exit-code -o "${output_dir}"
{
    echo "# Generated by scripts/generate-librasr-stubs.sh, do not edit manually."
    cat "${output_dir}/librasr.pyi"
} > src/Tools/LibRASR/librasr.pyi
