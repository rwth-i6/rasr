#ifndef _TEST_TOKENIZER_HH
#define _TEST_TOKENIZER_HH

#include <sstream>

#include <Test/File.hh>
#include <Test/UnitTest.hh>
#include <Tokenizer/Module.hh>

namespace Test {

/*
 * Creates tokenizers via the TokenizerFactory from the parameters set below `*.tokenizer`.
 * The test files in data/tokenizer are generated by data/tokenizer/generate.sh.
 */
class TokenizerFixture : public ConfigurableFixture {
public:
    virtual void setUp() {
        setParameter("*.channel", "nil");
        setParameter("*.error.channel", "stderr");
    }

protected:
    static std::string const text;  // Contains a word with characters that are not part of the training corpus

    void setTokenizerParameter(std::string const& name, std::string const& value) {
        setParameter("*.tokenizer." + name, value);
    }

    // Expected errors are counted instead of terminating and not printed, check them with `hasFatalErrors()`
    void delayErrors() {
        setTokenizerParameter("on-error", "delayed-exit");
        setTokenizerParameter("error.channel", "nil");
    }

    Tokenizer::TokenizerRef createTokenizer() const {
        return Tokenizer::Module::instance().tokenizerFactory().createTokenizer(select("tokenizer"));
    }

    // Space-separated string representation of token or id sequences for comparison and readable test failures
    template<typename T>
    static std::string join(std::vector<T> const& v) {
        std::ostringstream ss;
        for (size_t i = 0ul; i < v.size(); ++i) {
            ss << (i > 0ul ? " " : "") << v[i];
        }
        return ss.str();
    }
};

inline std::string const TokenizerFixture::text = "the newest lower tower is wider than straße xy";

}  // namespace Test

#endif  // _TEST_TOKENIZER_HH
